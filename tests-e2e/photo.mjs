// Profile photo: upload via the real picker → crop/downscale → persists after reopen → removed by local deletion.
import {chromium} from 'playwright';
const URL = 'http://localhost:8090/', OUT = process.env.OUT ?? 'tests-e2e/shots';
const results = [];
const check = (name, ok, info = '') => {results.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${info ? ' — ' + info : ''}`);};
const browser = await chromium.launch();
const page = await (await browser.newContext({viewport: {width: 390, height: 844}, deviceScaleFactor: 2})).newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto(URL);
await page.getByText('Start decoding').click();
await page.getByRole('button', {name: 'Edit your profile'}).first().click();
await page.getByText('Your picture').waitFor();
const chooser = page.waitForEvent('filechooser');
await page.getByRole('button', {name: 'Upload a profile photo'}).click();
await (await chooser).setFiles('tests-e2e/test-photo.jpg');
await page.getByRole('button', {name: 'Use my photo'}).waitFor({timeout: 15000});
check('photo picked, processed and stored', true);
await page.screenshot({path: `${OUT}/photo-edit-sheet.png`});
await page.getByText('Save my profile').click();
await page.waitForTimeout(600);
const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('genz-code-avatar-photo') || 'null'));
check('stored as small JPEG with checksum', stored && stored.data.startsWith('/9j/') && stored.data.length < 80000 && /^[0-9a-f]{8}$/.test(stored.sum), stored ? `${Math.round(stored.data.length * 0.75 / 1024)} KB` : 'missing');
const dims = await page.evaluate(() => new Promise(r => {const i = new Image(); i.onload = () => r([i.width, i.height]); i.src = 'data:image/jpeg;base64,' + JSON.parse(localStorage.getItem('genz-code-avatar-photo')).data;}));
check('downscaled and cropped to 320×320', dims[0] === 320 && dims[1] === 320, dims.join('×'));
await page.reload(); await page.waitForTimeout(2500);
await page.getByRole('tab', {name: /You/}).click(); await page.waitForTimeout(500);
const imgs = await page.locator('img[src^="data:image/jpeg"]').count();
check('photo shown in header and dashboard after reopen', imgs >= 2, `${imgs} photo images`);
await page.screenshot({path: `${OUT}/photo-dashboard.png`});
const v3 = await page.evaluate(() => localStorage.getItem('genz-code-v3'));
check('photo is not inside the synced learning record', !v3.includes('/9j/'));
// Switch back to an icon, then delete local data
await page.getByRole('button', {name: 'Edit your profile'}).first().click();
await page.getByRole('button', {name: 'Choose rocket avatar'}).click();
await page.getByText('Save my profile').click(); await page.waitForTimeout(500);
check('switching back to an icon hides the photo', (await page.locator('img[src^="data:image/jpeg"]').count()) === 0);
await page.getByText('Threat Shield', {exact: true}).first().click(); await page.waitForTimeout(800);
page.once('dialog', d => d.accept());
await page.getByRole('button', {name: 'Delete all data on this device'}).click(); await page.waitForTimeout(1200);
check('deleting local data removes the photo', (await page.evaluate(() => localStorage.getItem('genz-code-avatar-photo'))) === null);
check('no page errors', errors.length === 0, errors.slice(0, 2).join(' | '));
await browser.close();
console.log(`${results.filter(Boolean).length}/${results.length} checks passed`);
